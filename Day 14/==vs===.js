// == -> loosy condition check 

//for double == saying they are same, but we know they are different 
if(5 == "5"){
    console.log("Both are same");
}else{
    console.log("both are not same");
}

//for === giving the actual result 
if(5 === "5"){
    console.log("Both are same");
}else{
    console.log("both are not same");
}